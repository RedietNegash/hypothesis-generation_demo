import os
import subprocess

import pandas as pd
import pyranges as pr

CATLAS_BASE_URL = "https://catlas.org/humanenhancer/data/cCREs"
GENOME_BP = 3_100_000_000


def download(url: str, dest_path: str, description: str) -> bool:
    if os.path.exists(dest_path) and os.path.getsize(dest_path) > 1000:
        print(f"  Already exists: {dest_path}")
        return True
    print(f"  Downloading {description}...")
    result = subprocess.run(
        ["wget", "--continue", "--tries=5", "--timeout=120", "-O", dest_path, url]
    )
    ok = result.returncode == 0
    if ok:
        print(f"  Done: {dest_path} ({os.path.getsize(dest_path) / 1e6:.0f} MB)")
    return ok


def download_catlas_celltypes(catlas_dir: str, cell_types=None) -> list:
    """Download all (or a subset of) CATlas per-cell-type BED files. Skips files
    already on disk. Returns the list of cell types that downloaded successfully."""
    os.makedirs(catlas_dir, exist_ok=True)
    cell_types = cell_types or CELL_TYPES
    print(
        f"Downloading {len(cell_types)} CATlas cell-type BED files "
        f"(skips ones already on disk)..."
    )
    failed = []
    for i, cell_type in enumerate(cell_types):
        url = f"{CATLAS_BASE_URL}/{cell_type}.bed"
        dest = f"{catlas_dir}/{cell_type}.bed"
        ok = download(url, dest, f"CATlas {cell_type} cCREs")
        if not ok or not os.path.exists(dest) or os.path.getsize(dest) < 100:
            print(f"  FAILED: {cell_type}")
            failed.append(cell_type)
            if os.path.exists(dest):
                os.remove(dest)
        if (i + 1) % 25 == 0:
            print(f"  ...{i + 1}/{len(cell_types)}")
    if failed:
        print(f"\n{len(failed)} cell types failed to download: {failed}")
    ready = [c for c in cell_types if c not in failed]
    print(f"\n{len(ready)} cell types ready.")
    return ready


_peak_cache = {}


def get_celltype_peaks(cell_type: str, catlas_dir: str):

    cache_key = (catlas_dir, cell_type)
    if cache_key in _peak_cache:
        return _peak_cache[cache_key]
    path = f"{catlas_dir}/{cell_type}.bed"
    if not os.path.exists(path):
        _peak_cache[cache_key] = None
        return None
    bed = pd.read_csv(
        path, sep="\t", header=None, usecols=[0, 1, 2], names=["chrom", "start", "end"]
    )
    peaks = pr.PyRanges(
        chromosomes=bed["chrom"], starts=bed["start"], ends=bed["end"]
    ).merge()
    _peak_cache[cache_key] = peaks
    return peaks


def build_variant_pyranges(
    df_variants: pd.DataFrame, keep_idx: bool = True
) -> pr.PyRanges:

    chrom = df_variants["chr"].apply(
        lambda c: f"chr{c}" if not str(c).startswith("chr") else c
    )
    data = {
        "Chromosome": chrom.values,
        "Start": (df_variants["pos"] - 1).values,
        "End": df_variants["pos"].values,
    }
    if keep_idx:
        data["variant_idx"] = df_variants.index.values
    return pr.PyRanges(pd.DataFrame(data))
